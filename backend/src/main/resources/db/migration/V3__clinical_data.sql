-- Common clinical-record columns: provenance (+ clinician confirmation for AI-proposed data) and
-- "entered in error" state. Clinical records are never hard-deleted.

CREATE TABLE symptoms (
    id                      UUID PRIMARY KEY,
    encounter_id            UUID         NOT NULL REFERENCES encounters (id),
    patient_id              UUID         NOT NULL REFERENCES patients (id),
    concept_system          VARCHAR(30),
    concept_code            VARCHAR(50),
    concept_display         VARCHAR(200) NOT NULL,
    concept_verification    VARCHAR(40)  NOT NULL,
    presence                VARCHAR(10)  NOT NULL,
    onset_pattern           VARCHAR(20),
    onset_at                TIMESTAMPTZ,
    duration                VARCHAR(100),
    severity                INTEGER CHECK (severity BETWEEN 0 AND 10),
    location                VARCHAR(200),
    character               VARCHAR(200),
    radiation               VARCHAR(200),
    aggravating_factors     VARCHAR(500),
    relieving_factors       VARCHAR(500),
    associated_symptoms     VARCHAR(500),
    notes                   VARCHAR(2000),
    provenance              VARCHAR(30)  NOT NULL,
    source_detail           VARCHAR(200),
    recorded_by             VARCHAR(100) NOT NULL,
    recorded_at             TIMESTAMPTZ  NOT NULL,
    confirmed_by            VARCHAR(100),
    confirmed_at            TIMESTAMPTZ,
    entered_in_error        BOOLEAN      NOT NULL DEFAULT FALSE,
    entered_in_error_reason VARCHAR(500),
    entered_in_error_by     VARCHAR(100),
    entered_in_error_at     TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_symptoms_ai_confirmed CHECK (provenance <> 'AI_INFERRED' OR confirmed_by IS NOT NULL),
    CONSTRAINT ck_symptoms_concept CHECK (concept_code IS NULL OR concept_system IS NOT NULL)
);
CREATE INDEX ix_symptoms_encounter ON symptoms (encounter_id);

CREATE TABLE observations (
    id                      UUID PRIMARY KEY,
    encounter_id            UUID         NOT NULL REFERENCES encounters (id),
    patient_id              UUID         NOT NULL REFERENCES patients (id),
    category                VARCHAR(30)  NOT NULL,
    vital_sign_type         VARCHAR(40)  NOT NULL,
    concept_system          VARCHAR(30),
    concept_code            VARCHAR(50),
    concept_display         VARCHAR(200) NOT NULL,
    concept_verification    VARCHAR(40)  NOT NULL,
    numeric_value           NUMERIC(10, 3),
    text_value              VARCHAR(100),
    unit                    VARCHAR(30),
    measured_at             TIMESTAMPTZ  NOT NULL,
    provenance              VARCHAR(30)  NOT NULL,
    source_detail           VARCHAR(200),
    recorded_by             VARCHAR(100) NOT NULL,
    recorded_at             TIMESTAMPTZ  NOT NULL,
    confirmed_by            VARCHAR(100),
    confirmed_at            TIMESTAMPTZ,
    entered_in_error        BOOLEAN      NOT NULL DEFAULT FALSE,
    entered_in_error_reason VARCHAR(500),
    entered_in_error_by     VARCHAR(100),
    entered_in_error_at     TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_observations_value CHECK (numeric_value IS NOT NULL OR text_value IS NOT NULL),
    CONSTRAINT ck_observations_ai_confirmed CHECK (provenance <> 'AI_INFERRED' OR confirmed_by IS NOT NULL)
);
CREATE INDEX ix_observations_encounter ON observations (encounter_id, measured_at DESC);

CREATE TABLE lab_observations (
    id                      UUID PRIMARY KEY,
    encounter_id            UUID         NOT NULL REFERENCES encounters (id),
    patient_id              UUID         NOT NULL REFERENCES patients (id),
    test_coding_system      VARCHAR(30),
    test_code               VARCHAR(50),
    test_name               VARCHAR(200) NOT NULL,
    test_code_verification  VARCHAR(40)  NOT NULL,
    numeric_value           NUMERIC(14, 4),
    text_value              VARCHAR(500),
    unit                    VARCHAR(50),
    reference_range_low     NUMERIC(14, 4),
    reference_range_high    NUMERIC(14, 4),
    abnormal_flag           VARCHAR(20),
    abnormal_flag_source    VARCHAR(40)  NOT NULL,
    collected_at            TIMESTAMPTZ  NOT NULL,
    provenance              VARCHAR(30)  NOT NULL,
    source_detail           VARCHAR(200),
    recorded_by             VARCHAR(100) NOT NULL,
    recorded_at             TIMESTAMPTZ  NOT NULL,
    confirmed_by            VARCHAR(100),
    confirmed_at            TIMESTAMPTZ,
    entered_in_error        BOOLEAN      NOT NULL DEFAULT FALSE,
    entered_in_error_reason VARCHAR(500),
    entered_in_error_by     VARCHAR(100),
    entered_in_error_at     TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_labs_value CHECK (numeric_value IS NOT NULL OR text_value IS NOT NULL),
    CONSTRAINT ck_labs_code CHECK (test_code IS NULL OR test_coding_system IS NOT NULL),
    CONSTRAINT ck_labs_ai_confirmed CHECK (provenance <> 'AI_INFERRED' OR confirmed_by IS NOT NULL)
);
CREATE INDEX ix_labs_encounter ON lab_observations (encounter_id, collected_at DESC);

CREATE TABLE medications (
    id                      UUID PRIMARY KEY,
    patient_id              UUID         NOT NULL REFERENCES patients (id),
    encounter_id            UUID REFERENCES encounters (id),
    medication_name         VARCHAR(200) NOT NULL,
    coding_system           VARCHAR(30),
    code                    VARCHAR(50),
    dosage                  VARCHAR(100),
    frequency               VARCHAR(100),
    route                   VARCHAR(50),
    start_date              DATE,
    end_date                DATE,
    status                  VARCHAR(20)  NOT NULL,
    provenance              VARCHAR(30)  NOT NULL,
    source_detail           VARCHAR(200),
    recorded_by             VARCHAR(100) NOT NULL,
    recorded_at             TIMESTAMPTZ  NOT NULL,
    confirmed_by            VARCHAR(100),
    confirmed_at            TIMESTAMPTZ,
    entered_in_error        BOOLEAN      NOT NULL DEFAULT FALSE,
    entered_in_error_reason VARCHAR(500),
    entered_in_error_by     VARCHAR(100),
    entered_in_error_at     TIMESTAMPTZ,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_medications_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT ck_medications_ai_confirmed CHECK (provenance <> 'AI_INFERRED' OR confirmed_by IS NOT NULL)
);
CREATE INDEX ix_medications_patient ON medications (patient_id);

